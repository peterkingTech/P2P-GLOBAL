// Generates migrations/221_gospel_salvation_seven_books.sql from
// gospel_salvation_v2.json (parsed verbatim from the owner's "Pre-Salvation
// Core Curriculum — Complete Simplified Teaching Edition").
//   node gospel_salvation_v2_sql.mjs gospel_salvation_v2.json ../../migrations/221_gospel_salvation_seven_books.sql
// Every id is derived from a fixed name (stable across runs), every insert is
// "on conflict do nothing" and every update is guarded, so applying the file
// twice changes nothing the second time.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const [, , inFile, outFile] = process.argv;
const data = JSON.parse(readFileSync(inFile, "utf8"));
const GOSPEL = "f6a2b3f6-b66d-45d6-8065-c46d7b63441b"; // The Gospel & Salvation (production)
const COLOR = "#C0392B";

// Name-based UUID (version 5 layout) so the file is reproducible.
const uuid = (name) => {
  const h = createHash("sha1").update(`p2p-gospel-salvation-v2:${name}`).digest();
  h[6] = (h[6] & 0x0f) | 0x50; h[8] = (h[8] & 0x3f) | 0x80;
  const x = h.subarray(0, 16).toString("hex");
  return `${x.slice(0, 8)}-${x.slice(8, 12)}-${x.slice(12, 16)}-${x.slice(16, 20)}-${x.slice(20)}`;
};
// Dollar-quoted text; the tag never appears in the content (checked).
const s = (v) => { if (v == null) return "null"; const t = String(v); if (t.includes("$gs$")) throw new Error("tag clash"); return `$gs$${t}$gs$`; };
const j = (o) => `${s(JSON.stringify(o))}::jsonb`;

const ARCHIVE = uuid("archived-curriculum");
const moduleIds = [], lessonIds = [];
const out = [];
out.push(`-- 221: The Gospel & Salvation — replaced with the owner's seven-book curriculum
-- ("Pre-Salvation Core Curriculum — Complete Simplified Teaching Edition"):
-- 7 books × 4 modules × 3 lessons = 28 modules, 84 lessons. DATA ONLY — no
-- schema change. Generated by lib/db/gospel_salvation_v2_sql.mjs from
-- lib/db/gospel_salvation_v2.json (parsed verbatim by
-- lib/db/gospel_salvation_v2_parse.mjs; only page footers removed).
--
-- Nothing is deleted. The previous 4 modules / 17 lessons (and the one
-- submission + review on them) are MOVED, unchanged, into a hidden archived
-- curriculum "The Gospel & Salvation (previous edition)"; the 4 modules are
-- marked 'archived'. They no longer appear anywhere but can be restored.
-- At apply time nobody had progress in the previous lessons (checked).
--
-- Each new lesson is stored the way the learner lesson screen reads it
-- (p2p_lesson_sections, p2p_scriptures, p2p_reflection_questions,
-- p2p_assignments + questions = the Comprehensive Check) and the way the
-- admin Block Editor reads it (p2p_lesson_blocks).
-- Each module's description starts "Book N · <book>" so the books read in
-- order in every app version.
--
-- Rollback (restores the previous edition exactly; the new rows stay but
-- are hidden):
--   update public.p2p_modules set curriculum_id = '${ARCHIVE}' where curriculum_id = '${GOSPEL}' and id in (<the 28 ids below>);
--   update public.p2p_modules set curriculum_id = '${GOSPEL}', status = 'published' where curriculum_id = '${ARCHIVE}' and id not in (<the 28 ids>);
--   update public.p2p_curriculums set description = <previous description, saved below> where id = '${GOSPEL}';

begin;

-- Previous description, kept for rollback:
--   ${(data.previousDescription ?? "").replace(/\n/g, " ")}

-- 1. A hidden home for the previous edition (archived, never listed).
insert into public.p2p_curriculums (id, title, description, type, status, is_visible, color_theme, admin_notes)
values ('${ARCHIVE}', ${s("The Gospel & Salvation (previous edition)")}, ${s("Archived 4-module edition, replaced by the seven-book curriculum (migration 221). Kept for history; not shown to learners.")},
  'core', 'archived', false, ${s(COLOR)}, ${s("Archived by migration 221. Restore: see the rollback note in migrations/221_gospel_salvation_seven_books.sql.")})
on conflict (id) do nothing;
`);

// Collect new module ids first (the move must exclude them).
for (const b of data.books) b.modules.forEach((_m, mi) => moduleIds.push(uuid(`module:${b.number}.${mi + 1}`)));
const idList = moduleIds.map((x) => `'${x}'`).join(", ");
out.push(`-- 2. Move the previous modules into the hidden archived course and archive the
--    modules. Their lessons keep their status: older lessons have no editor
--    blocks, so once archived they could not be re-published by a rollback.
--    Guarded: a second run finds none.
update public.p2p_modules set curriculum_id = '${ARCHIVE}', status = 'archived'
  where curriculum_id = '${GOSPEL}' and id not in (${idList});

-- 3. The course itself.
update public.p2p_curriculums set description = ${s("Seven books that walk from life before Christ to a lifetime of following Him: Pre-Salvation, Jesus Christ, The Gospel, Responding to the Gospel, Assurance of Salvation, Baptism and Identification With Christ, and From Convert to Disciple.")}
  where id = '${GOSPEL}';
`);

let order = 0;
for (const b of data.books) {
  out.push(`\n-- ═══ Book ${b.number}: ${b.title} ═══`);
  b.modules.forEach((mod, mi) => {
    order += 1;
    const mid = uuid(`module:${b.number}.${mi + 1}`);
    out.push(`insert into public.p2p_modules (id, curriculum_id, title, description, order_index, status, color_theme)
values ('${mid}', '${GOSPEL}', ${s(mod.title)}, ${s(`Book ${b.number} · ${b.title} — ${b.description}`)}, ${order}, 'published', ${s(COLOR)})
on conflict (id) do nothing;`);
    mod.lessons.forEach((l, li) => {
      const key = `${b.number}.${l.number}`;
      const lid = uuid(`lesson:${key}`);
      lessonIds.push(lid);
      const aid = uuid(`assignment:${key}`);
      const sections = [
        ["Definition and simple explanation", l.explanation],
        ["What this means and why it matters", l.matters],
        ["Important things to remember", l.remember.map((x) => `• ${x}`).join("\n")],
        ["Practical application", l.application],
      ];
      out.push(`-- Lesson ${b.number}.${l.number}: ${l.title}
insert into public.p2p_lessons (id, module_id, title, subtitle, order_index, status, estimated_minutes, published_at, version)
values ('${lid}', '${mid}', ${s(l.title)}, ${s(`Book ${b.number} · Lesson ${l.number}`)}, ${li + 1}, 'published', 10, now(), 1)
on conflict (id) do nothing;
insert into public.p2p_scriptures (id, lesson_id, reference, verse, display_order)
values ('${uuid(`scripture:${key}`)}', '${lid}', ${s(l.scripture.reference)}, ${s(l.scripture.text)}, 0)
on conflict (id) do nothing;
insert into public.p2p_lesson_sections (id, lesson_id, section_order, section_type, title, content) values
${sections.map(([t, c], i) => `  ('${uuid(`section:${key}:${i + 1}`)}', '${lid}', ${i + 1}, 'teaching', ${s(t)}, ${s(c)})`).join(",\n")}
on conflict (id) do nothing;
insert into public.p2p_reflection_questions (id, lesson_id, question, display_order) values
${l.reflection.map((q, i) => `  ('${uuid(`reflection:${key}:${i + 1}`)}', '${lid}', ${s(q)}, ${i + 1})`).join(",\n")}
on conflict (id) do nothing;
insert into public.p2p_assignments (id, lesson_id, title, instructions)
values ('${aid}', '${lid}', ${s("Comprehensive Check")}, ${s("")})
on conflict (id) do nothing;
insert into public.p2p_assignment_questions (id, assignment_id, question, display_order) values
${l.check.map((q, i) => `  ('${uuid(`check:${key}:${i + 1}`)}', '${aid}', ${s(q)}, ${i + 1})`).join(",\n")}
on conflict (id) do nothing;
insert into public.p2p_lesson_blocks (id, lesson_id, block_type, content, order_index, is_required, is_submittable) values
  ('${uuid(`block:${key}:verse`)}', '${lid}', 'memory_verse', ${j({ reference: l.scripture.reference, text: l.scripture.text, translation: "" })}, 0, true, false),
${sections.map(([t, c], i) => `  ('${uuid(`block:${key}:p${i + 1}`)}', '${lid}', 'paragraph', ${j({ text: `${t}\n\n${c}` })}, ${i + 1}, false, false)`).join(",\n")},
${l.reflection.map((q, i) => `  ('${uuid(`block:${key}:r${i + 1}`)}', '${lid}', 'reflection_question', ${j({ question: q })}, ${5 + i}, true, true)`).join(",\n")},
  ('${uuid(`block:${key}:check`)}', '${lid}', 'assignment', ${j({ title: "Comprehensive Check", instructions: "", due_after_days: 7, questions: l.check.map((q) => ({ question: q })) })}, 8, true, true)
on conflict (id) do nothing;`);
    });
  });
}

out.push(`
commit;

-- New module ids (for rollback): ${moduleIds.join(", ")}
`);
writeFileSync(outFile, out.join("\n"));
writeFileSync(outFile.replace(/\.sql$/, ".ids.json"), JSON.stringify({ gospel: GOSPEL, archive: ARCHIVE, modules: moduleIds, lessons: lessonIds }, null, 2));
console.log(`wrote ${outFile}: ${moduleIds.length} modules, ${lessonIds.length} lessons`);
