// Generates migrations/223_bible_translations_plan.sql: the translations the
// owner's API.Bible plan includes — English KJV (already on), The Message and
// the Amplified Bible — plus the newest COMPLETE Bible (all 66 books, checked
// against the API) for every app language that has one in the plan.
// Each row's license_notes is the publisher's own copyright line from
// API.Bible; the reader allows copying verse text only for public-domain ones
// (lib/bibleReader.ts textCopyAllowed).
//   node bible_translations_223.mjs <api-server .env> ../../migrations/223_bible_translations_plan.sql
import { readFileSync, writeFileSync } from "node:fs";

const [, , envFile, outFile] = process.argv;
const key = readFileSync(envFile, "utf8").match(/^API_BIBLE_KEY=(.*)$/m)[1].trim().replace(/^["']|["']$/g, "");

// language (p2p_languages.code), code, name, API.Bible id, default for its language.
// Not added (and why) is listed at the end of the migration.
const ROWS = [
  ["en", "MSG", "The Message", "6f11a7de016f942e-01", false],
  ["en", "AMP", "Amplified Bible", "a81b73293d3080c9-01", false],
  ["de", "ELO", "German Elberfelder Bible (1905, unrevised)", "95410db44ef800c1-01", false],
  ["es", "VBL", "Versión Biblia Libre (2022)", "482ddd53705278cc-02", true],
  ["es", "PDDPT", "Palabra de Dios para ti (2020)", "48acedcf8595c754-01", false],
  ["bn", "BCV", "Bengali Contemporary Version (2019)", "efd8a351a07d4264-01", true],
  ["fa", "OPCB", "Persian Contemporary Bible (2022)", "7cd100148df29c08-01", true],
  ["ig", "BIUO", "Igbo Contemporary Bible (2020)", "a36fc06b086699f1-02", true],
  ["it", "DB1885", "Diodati Bible (1885)", "41f25b97f468e10b-01", true],
  ["nl", "NLD1939", "Dutch Bible (1939, Petrus Canisius)", "ead7b4cc5007389c-01", true],
  ["pl", "UBG", "Updated Gdańsk Bible (2018)", "1c9761e0230da6e0-01", true],
  ["ta", "OTCV", "Tamil Contemporary Version (2022)", "032ec262506b719f-01", true],
  ["te", "OTSA", "Telugu Contemporary Version (2024)", "81d6933d39d343f8-03", true],
  ["th", "TCV", "Thai Common Version (2025)", "a62f327aa0179709-01", true],
  ["tr", "YTC", "Literal Turkish Translation (2024)", "085defac6e17b9eb-01", true],
  ["ur", "OUCV", "Urdu Contemporary Version (2024)", "eecbca904435fce9-01", true],
  ["vi", "OVCB", "Vietnamese Contemporary Bible (2015)", "5cc7093967a0a392-01", true],
  ["yo", "BMYO", "Yoruba Contemporary Bible (2017)", "b8d1feac6e94bd74-01", true],
  ["zh", "OCCB", "Chinese Contemporary Bible, Simplified (2022)", "7ea794434e9ea7ee-01", true],
  ["zh-TW", "OCCBT", "Chinese Contemporary Bible, Traditional (2023)", "a6e06d2c5b90ad89-01", true],
];
const s = (v) => { const t = String(v); if (t.includes("$bt$")) throw new Error("tag"); return `$bt$${t}$bt$`; };
const clean = (h) => String(h ?? "").replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim();

const lines = [];
for (const [lang, code, name, id, isDefault] of ROWS) {
  const r = await fetch(`https://api.scripture.api.bible/v1/bibles/${id}`, { headers: { "api-key": key } });
  if (!r.ok) throw new Error(`${code}: HTTP ${r.status}`);
  const info = (await r.json()).data;
  const books = (await (await fetch(`https://api.scripture.api.bible/v1/bibles/${id}/books`, { headers: { "api-key": key } })).json()).data ?? [];
  const has = new Set(books.map((b) => b.id));
  if (!["GEN", "PSA", "MAL", "MAT", "REV"].every((b) => has.has(b)) || books.length < 66) throw new Error(`${code}: not a complete Bible (${books.length} books)`);
  const notes = `${clean(info.copyright)} — in the owner's API.Bible plan (checked 2026-11-02).`;
  lines.push({ lang, code, name, id, isDefault, notes });
}

const out = [`-- 223: Bible translations from the owner's API.Bible plan. DATA ONLY.
-- English: KJV (already on) + The Message (MSG) + Amplified Bible (AMP).
-- Every other app language: the newest COMPLETE Bible (66 books, checked) the
-- plan includes. German: the plan has only Luther 1912 (already on, kept as
-- default — the newest German text available), Elberfelder 1905 and
-- Textbibel 1906; Elberfelder is added. Spanish: the 2022 Versión Biblia
-- Libre becomes the default (Reina-Valera 1909 stays available).
-- Generated by lib/db/bible_translations_223.mjs; license_notes is each
-- publisher's copyright line from API.Bible (copying verse text is allowed
-- only for public-domain translations). Only references are ever stored —
-- people's saved highlights/notes keep their own translation.
-- Rollback: delete the rows with the codes below; set RVR09 default again.

begin;
-- Spanish default moves to the 2022 translation (one default per language).
update public.p2p_bible_translations set is_default_for_language = false where translation_code = 'RVR09' and is_default_for_language;
`];
for (const x of lines) {
  out.push(`insert into public.p2p_bible_translations (language, translation_code, translation_name, is_default_for_language, provider, api_bible_id, license_notes, is_licensed_confirmed)
values ('${x.lang}', '${x.code}', ${s(x.name)}, ${x.isDefault}, 'api.bible', '${x.id}', ${s(x.notes)}, true)
on conflict (translation_code) do nothing;`);
}
out.push(`
commit;

-- Not added:
--   • New Testament only in the plan (the reader needs all 66 books): Hausa (OSRK), Hebrew (HDZP), Norwegian (OELB),
--     Ukrainian (New Testament + Psalms), Polish Słowo Życia NT, Portuguese Translation for Translators NT.
--   • Indonesian TSI: 62 of 66 books.
--   • Punjabi (OPCV 2025) and Twi (Akuapem 2020): complete, but pa / tw aren't in p2p_languages yet.
--   • No translation in the plan: Afrikaans, Danish, Japanese, Korean, Malay, Romanian, Russian, Swedish, Tagalog, Zulu;
--     Greek is only ancient (New Testament / Septuagint) texts.
--   • Modern German (Luther 2017, Elberfelder 2006, Schlachter 2000, Hoffnung für alle) is not in the plan.
`);
writeFileSync(outFile, out.join("\n"));
console.log(`wrote ${outFile}: ${lines.length} translations`);
for (const x of lines) console.log(`  ${x.lang.padEnd(6)} ${x.code.padEnd(8)} default=${x.isDefault} | ${x.notes.slice(0, 80)}`);
