// Generates migrations/222_gospel_salvation_full_content.sql: adds ALL the
// remaining content from the owner's files to the 84 lessons migration 221
// created (gospel_salvation_v3_extras.json, parsed by
// gospel_salvation_v3_extras.mjs). DATA ONLY; nothing is deleted.
//   node gospel_salvation_v3_sql.mjs gospel_salvation_v2.json gospel_salvation_v3_extras.json ../../migrations/222_gospel_salvation_full_content.sql
// Ids are the same name-based ids 221 used (existing rows) or new fixed ones;
// inserts are "on conflict do nothing" and updates only change rows that
// still differ, so a second run changes nothing.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const [, , v2File, extrasFile, outFile] = process.argv;
const v2 = JSON.parse(readFileSync(v2File, "utf8"));
const x = JSON.parse(readFileSync(extrasFile, "utf8"));
const GOSPEL = "f6a2b3f6-b66d-45d6-8065-c46d7b63441b";
const uuid = (name) => {
  const h = createHash("sha1").update(`p2p-gospel-salvation-v2:${name}`).digest();
  h[6] = (h[6] & 0x0f) | 0x50; h[8] = (h[8] & 0x3f) | 0x80;
  const s = h.subarray(0, 16).toString("hex");
  return `${s.slice(0, 8)}-${s.slice(8, 12)}-${s.slice(12, 16)}-${s.slice(16, 20)}-${s.slice(20)}`;
};
const s = (v) => { if (v == null) return "null"; const t = String(v); if (t.includes("$gs$")) throw new Error("tag clash"); return `$gs$${t}$gs$`; };
const j = (o) => `${s(JSON.stringify(o))}::jsonb`;
const numbered = (list) => list.map((v, i) => `${i + 1}. ${v}`).join("\n");
const bulleted = (list) => list.map((v) => `• ${v}`).join("\n");
const slug = (t) => t.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 40);
const words = (t) => (t.match(/\S+/g) ?? []).length;

const out = [`-- 222: The Gospel & Salvation — ALL the content of the owner's files, added to
-- the 84 lessons of migration 221 (which carried the Simplified Teaching
-- Edition). DATA ONLY — no schema change; nothing deleted. Generated by
-- lib/db/gospel_salvation_v3_sql.mjs from lib/db/gospel_salvation_v3_extras.json
-- (parsed verbatim by lib/db/gospel_salvation_v3_extras.mjs; only page
-- numbers/footers removed).
--
-- Added from the seven book files (1_Pre-Salvation … 7_From_Convert_to_Disciple):
--   • first lesson of each book: About this book, Root Scripture, Lecture;
--   • every lesson: two study questions with answers, Important Distinction,
--     5 Personal Reflections, the 5-step Lesson Assignment.
-- Added from "The Gospel Of Jesus Christ" (Book 3 in full):
--   • first lesson of each module: About this module, Main Scripture
--     references, Module objectives;
--   • every Book 3 lesson: Main Scriptures, the full teaching (Introduction and
--     numbered sections), its Personal Reflection questions, Lesson Summary;
--   • last lesson of Module 4: the Module 4 completion review.
-- Added from "New Teaching Approach": the sample Lesson 1.1 (to Book 1,
-- Lesson 1.1: key passage, definition, simple explanation, why it matters,
-- things to understand, reflections, check questions, practical application);
-- the editorial framework and teaching note go to the course's admin notes.
--
-- Section order in every lesson (existing sections are re-numbered, not changed):
--   book / module introduction → explanation → why it matters → [sample 1.1]
--   → [Book 3 full teaching] → study questions → Important Distinction
--   → things to remember → [Book 3 summary] → Lesson Assignment → practical
--   application → [Module 4 review].
-- Rollback: the rows added here have the ids listed in
-- 222_gospel_salvation_full_content.ids.json; deleting them and restoring
-- section_order 1–4 / block order 0–8 / the 1.1 check block returns 221's state
-- (restore-tested).

begin;
`];
const added = { sections: [], reflections: [], checks: [], blocks: [] };

v2.books.forEach((book) => {
  const B = x.books[book.number];
  book.modules.forEach((mod, mi) => {
    const mNum = mi + 1;
    mod.lessons.forEach((l, li) => {
      const key = `${book.number}.${l.number}`;
      const lid = uuid(`lesson:${key}`);
      const sep = B.lessons[l.number];
      const g = book.number === 3 ? x.gospel.lessons[l.number] : null;
      const gm = book.number === 3 ? x.gospel.modules[mNum] : null;
      const sample = book.number === 1 && l.number === "1.1" ? x.approach.sample : null;
      // The full, ordered list of sections: existing ones by their 221 index, new ones with content.
      const seq = [];
      const add = (name, title, content) => { if (content && content.trim()) seq.push({ id: uuid(`section:${key}:x:${name}`), title, content, isNew: true }); };
      const old = (i) => seq.push({ id: uuid(`section:${key}:${i}`), isNew: false, i });
      if (l.number === "1.1") {
        add("book-about", "About this book", B.description);
        add("book-root", "Root Scripture", B.rootScripture);
        add("book-lecture", "Lecture", B.lecture);
      }
      if (gm && li === 0) {
        add("module-about", "About this module", gm.description.join("\n\n"));
        add("module-refs", "Main Scripture references", bulleted(gm.scriptureReferences));
        add("module-objectives", "Module objectives", [gm.objectivesIntro, numbered(gm.objectives)].filter(Boolean).join("\n\n"));
      }
      old(1); old(2);
      if (sample) {
        add("sample-passage", "Key Bible passage", sample.keyPassage);
        add("sample-definition", `Definition: ${sample.definitionTitle}`, sample.definition);
        add("sample-explanation", "Simple explanation", bulleted(sample.explanation));
        add("sample-important", "Why is this important?", sample.important);
        add("sample-understand", "Important things to understand", bulleted(sample.understand));
      }
      if (g) {
        add("g-main", "Main Scriptures", g.mainScriptures);
        g.sections.forEach((sec) => add(`g-${slug(sec.title)}`, sec.title, sec.content));
      }
      sep.qa.forEach((qa, i) => add(`study-${i + 1}`, `Study question ${i + 1}`, `${qa.q}\n\n${qa.a}`));
      add("distinction", "Important Distinction", sep.distinction);
      old(3);
      if (g) add("g-summary", "Lesson Summary", g.summary);
      add("assignment", "Lesson Assignment", numbered(sep.assignment));
      if (sample) add("sample-application", "Practical application (sample lesson)", sample.application);
      old(4);
      if (gm?.review && li === 2 && mNum === 4) {
        add("review-truths", "Module 4 review: Key truths to remember", numbered(gm.review.keyTruths));
        add("review-questions", "Module 4 review: Questions", numbered(gm.review.reviewQuestions));
        add("review-application", "Module 4 review: Practical application", gm.review.practicalApplication);
      }

      out.push(`\n-- Book ${book.number} · Lesson ${l.number}: ${l.title}`);
      const newSecs = seq.filter((q) => q.isNew);
      if (newSecs.length) {
        out.push(`insert into public.p2p_lesson_sections (id, lesson_id, section_order, section_type, title, content) values\n${newSecs.map((q) => `  ('${q.id}', '${lid}', ${seq.indexOf(q) + 1}, 'teaching', ${s(q.title)}, ${s(q.content)})`).join(",\n")}\non conflict (id) do nothing;`);
        added.sections.push(...newSecs.map((q) => q.id));
      }
      for (const q of seq.filter((q) => !q.isNew)) {
        const n = seq.indexOf(q) + 1;
        if (n !== q.i) out.push(`update public.p2p_lesson_sections set section_order = ${n} where id = '${q.id}' and section_order <> ${n};`);
      }
      // Personal Reflections: 221's 3, then the book file's 5, Book 3's questions, the sample's.
      const refl = [...sep.reflection, ...(g ? g.reflection : []), ...(sample ? sample.reflection : [])];
      out.push(`insert into public.p2p_reflection_questions (id, lesson_id, question, display_order) values\n${refl.map((q, i) => `  ('${uuid(`reflection:${key}:x:${i + 1}`)}', '${lid}', ${s(q)}, ${4 + i})`).join(",\n")}\non conflict (id) do nothing;`);
      added.reflections.push(...refl.map((_q, i) => uuid(`reflection:${key}:x:${i + 1}`)));
      // Comprehensive Check: the sample lesson's questions join 1.1's four.
      if (sample) {
        out.push(`insert into public.p2p_assignment_questions (id, assignment_id, question, display_order) values\n${sample.check.map((q, i) => `  ('${uuid(`check:${key}:x:${i + 1}`)}', '${uuid(`assignment:${key}`)}', ${s(q)}, ${5 + i})`).join(",\n")}\non conflict (id) do nothing;`);
        added.checks.push(...sample.check.map((_q, i) => uuid(`check:${key}:x:${i + 1}`)));
      }
      // Editor blocks, in the same order as the lesson: verse, every section, every reflection, the check.
      let order = 1;
      const blockSql = [];
      const newBlocks = [];
      for (const q of seq) {
        if (q.isNew) newBlocks.push(`  ('${uuid(`block:${key}:x:${q.id}`)}', '${lid}', 'paragraph', ${j({ text: `${q.title}\n\n${q.content}` })}, ${order}, false, false)`);
        else blockSql.push(`update public.p2p_lesson_blocks set order_index = ${order} where id = '${uuid(`block:${key}:p${q.i}`)}' and order_index <> ${order};`);
        if (q.isNew) added.blocks.push(uuid(`block:${key}:x:${q.id}`));
        order++;
      }
      for (let i = 1; i <= 3; i++) { blockSql.push(`update public.p2p_lesson_blocks set order_index = ${order} where id = '${uuid(`block:${key}:r${i}`)}' and order_index <> ${order};`); order++; }
      refl.forEach((q, i) => { newBlocks.push(`  ('${uuid(`block:${key}:xr${i + 1}`)}', '${lid}', 'reflection_question', ${j({ question: q })}, ${order}, true, true)`); added.blocks.push(uuid(`block:${key}:xr${i + 1}`)); order++; });
      blockSql.push(`update public.p2p_lesson_blocks set order_index = ${order} where id = '${uuid(`block:${key}:check`)}' and order_index <> ${order};`);
      if (sample) {
        const all = [...l.check, ...sample.check].map((q) => ({ question: q }));
        blockSql.push(`update public.p2p_lesson_blocks set content = jsonb_set(content, '{questions}', ${j(all)}) where id = '${uuid(`block:${key}:check`)}' and jsonb_array_length(content->'questions') <> ${all.length};`);
      }
      out.push(`insert into public.p2p_lesson_blocks (id, lesson_id, block_type, content, order_index, is_required, is_submittable) values\n${newBlocks.join(",\n")}\non conflict (id) do nothing;`);
      out.push(...blockSql);
      // Reading time from the whole lesson (about 180 words a minute, rounded to 5).
      const text = [l.explanation, l.matters, l.remember.join(" "), l.application, ...newSecs.map((q) => q.content)].join(" ");
      const minutes = Math.max(10, Math.round(words(text) / 180 / 5) * 5);
      out.push(`update public.p2p_lessons set estimated_minutes = ${minutes} where id = '${lid}' and estimated_minutes is distinct from ${minutes};`);
    });
  });
});

// The editorial framework and teaching note: for the people who edit the course.
const notes = `Teaching approach (from "Pre-Salvation Curriculum — New Teaching Approach", migration 222):\n\n${x.approach.framework}\n\nTeaching note (sample lesson): ${x.approach.sample.teachingNote}`;
out.push(`\n-- Course admin notes: the editorial framework (only if none are set).
update public.p2p_curriculums set admin_notes = ${s(notes)} where id = '${GOSPEL}' and admin_notes is null;

commit;
`);
writeFileSync(outFile, out.join("\n"));
writeFileSync(outFile.replace(/\.sql$/, ".ids.json"), JSON.stringify(added, null, 2));
console.log(`wrote ${outFile}: +${added.sections.length} sections, +${added.reflections.length} reflections, +${added.checks.length} check questions, +${added.blocks.length} blocks`);
