// Generates migrations/224_twi_language_and_bible.sql: Twi (tw) in the language
// list (p2p_languages — the app already ships a Twi interface, lib/i18n.ts),
// and the two complete Twi Bibles in the owner's API.Bible plan.
//   node twi_224.mjs <api-server .env> ../../migrations/224_twi_language_and_bible.sql
import { readFileSync, writeFileSync } from "node:fs";

const [, , envFile, outFile] = process.argv;
const key = readFileSync(envFile, "utf8").match(/^API_BIBLE_KEY=(.*)$/m)[1].trim().replace(/^["']|["']$/g, "");
const BIBLES = [
  ["WAKNA", "Akuapem Twi Contemporary Bible (2020)", "b6aee081108c0bc6-01", true],
  ["WASNA", "Asante Twi Contemporary Bible (2020)", "18f6cf27f7b43297-01", false],
];
const s = (v) => { const t = String(v); if (t.includes("$tw$")) throw new Error("tag"); return `$tw$${t}$tw$`; };
const clean = (h) => String(h ?? "").replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim();
const rows = [];
for (const [code, name, id, isDefault] of BIBLES) {
  const info = (await (await fetch(`https://api.scripture.api.bible/v1/bibles/${id}`, { headers: { "api-key": key } })).json()).data;
  const books = (await (await fetch(`https://api.scripture.api.bible/v1/bibles/${id}/books`, { headers: { "api-key": key } })).json()).data ?? [];
  const has = new Set(books.map((b) => b.id));
  if (books.length < 66 || !["GEN", "PSA", "MAL", "MAT", "REV"].every((b) => has.has(b))) throw new Error(`${code}: not a complete Bible (${books.length} books)`);
  rows.push({ code, name, id, isDefault, notes: `${clean(info.copyright)} — in the owner's API.Bible plan (checked 2026-11-02).` });
}
writeFileSync(outFile, `-- 224: Twi (tw) in the language list, and the complete Twi Bibles. DATA ONLY.
-- The app already offers a Twi interface (lib/i18n.ts, locales/tw.json); the
-- database list (p2p_languages: sign-up language, content translation, Bible
-- languages) did not have it. Same shape as the other African languages
-- (yo / ig / ha): not yet active for automatic content translation, UI
-- translation unreviewed. Generated by lib/db/twi_224.mjs.
-- Rollback: delete the two Bible rows, then the language row (nothing else
-- references it at apply time).

begin;
insert into public.p2p_languages (code, name, is_default, name_en, name_native, flag_emoji, is_rtl, is_active, sort_order, ui_review_status)
values ('tw', 'Twi', false, 'Twi (Akan)', 'Twi', ${s("🇬🇭")}, false, false, 40, 'unreviewed')
on conflict (code) do nothing;
${rows.map((x) => `insert into public.p2p_bible_translations (language, translation_code, translation_name, is_default_for_language, provider, api_bible_id, license_notes, is_licensed_confirmed)
values ('tw', '${x.code}', ${s(x.name)}, ${x.isDefault}, 'api.bible', '${x.id}', ${s(x.notes)}, true)
on conflict (translation_code) do nothing;`).join("\n")}
commit;
`);
console.log(`wrote ${outFile}`); for (const x of rows) console.log(" ", x.code, x.isDefault, x.notes.slice(0, 90));
