// Build the Explore Scripture by Topic outputs from the editorial collection (data/scripture-topics/*.json):
//   • data/scripture-topics/categories.json   — category list + topic title → category (bundled by the API)
//   • docs/proposals/248_scripture_topics_expansion_PROPOSED.sql — the database change, NOT applied
//   • docs/scripture-topics-review.md         — the editorial review report (counts, shared passages, validation)
//   node --experimental-strip-types scripts/build-scripture-topics.mjs
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parsePassage, slugify } from "../src/lib/scriptureTopics.ts";

const here = path.dirname(fileURLToPath(import.meta.url));
const dataDir = path.join(here, "..", "data", "scripture-topics");
const repo = path.join(here, "..", "..", "..");
const index = JSON.parse(readFileSync(path.join(dataDir, "index.json"), "utf8"));
const report = JSON.parse(readFileSync(path.join(dataDir, "validation-report.json"), "utf8"));
const files = readdirSync(dataDir).filter((f) => f.endsWith(".json") && !["index.json", "verse-counts.json", "validation-report.json", "categories.json"].includes(f)).sort();

const newTopics = [], additions = [], problems = [];
for (const f of files) {
  const j = JSON.parse(readFileSync(path.join(dataDir, f), "utf8"));
  for (const t of j.topics ?? []) newTopics.push({ ...t, category: j.category, parsed: t.passages.map(parsePassage) });
  for (const t of j.existingTopicAdditions ?? []) additions.push({ ...t, category: index.existingTopicCategories[t.title], parsed: t.passages.map(parsePassage) });
}
const existingTitles = Object.keys(index.existingTopicCategories);
// Checks: unique slugs/titles, no new topic duplicating an existing one, no duplicate passage inside a topic, all parsed.
const slugs = new Set(), titles = new Set(existingTitles.map((x) => x.toLowerCase()));
for (const t of newTopics) {
  if (slugs.has(t.slug)) problems.push(`duplicate slug ${t.slug}`); slugs.add(t.slug);
  if (t.slug !== slugify(t.title)) problems.push(`slug ${t.slug} does not match its title (${slugify(t.title)})`);
  if (titles.has(t.title.toLowerCase())) problems.push(`topic "${t.title}" duplicates an existing or new topic`); titles.add(t.title.toLowerCase());
}
for (const t of additions) if (!existingTitles.includes(t.title)) problems.push(`addition for unknown existing topic "${t.title}"`);
for (const t of [...newTopics, ...additions]) {
  const keys = new Set();
  for (const p of t.parsed) { if (!p.ok) problems.push(`${t.title}: ${p.reason}`); else { if (keys.has(p.key)) problems.push(`${t.title}: duplicate passage ${p.display}`); keys.add(p.key); } }
}
if (problems.length) { console.log(problems.join("\n")); process.exit(1); }

// Shared passages (one reference row, several topics).
const byKey = new Map();
for (const t of [...newTopics, ...additions]) for (const p of t.parsed) { const e = byKey.get(p.key) ?? { p, topics: [] }; e.topics.push(t.title); byKey.set(p.key, e); }
const shared = [...byKey.values()].filter((e) => e.topics.length > 1).sort((a, b) => b.topics.length - a.topics.length || a.p.display.localeCompare(b.p.display));

// 1. categories.json
const byTitle = { ...index.existingTopicCategories };
for (const t of newTopics) byTitle[t.title] = t.category;
writeFileSync(path.join(dataDir, "categories.json"), JSON.stringify({ categories: index.categories, byTitle }, null, 1) + "\n");

// 2. Proposed SQL.
const q = (s) => (s === null || s === undefined ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const refRows = [...byKey.values()].map((e) => `(${q(e.p.book)}, ${e.p.chapter}, ${e.p.startVerse}, ${e.p.endVerse}, ${q(e.p.display)})`);
const linkRows = [];
for (const t of [...newTopics, ...additions]) t.parsed.forEach((p, i) => linkRows.push(`(${q(t.title)}, ${q(p.book)}, ${p.chapter}, ${p.startVerse}, ${p.endVerse}, ${i + 1}, ${q(p.title)}, ${q(p.kind)}, ${q(p.note)})`));
const sql = `-- ╔══════════════════════════════════════════════════════════════════════════╗
-- ║ PROPOSED — NOT APPLIED. Generated by scripts/build-scripture-topics.mjs.   ║
-- ║ Needs the owner's approval AND editorial review before it is applied.      ║
-- ╚══════════════════════════════════════════════════════════════════════════╝
-- Explore Scripture by Topic expansion. ADDITIVE ONLY: no existing topic, reference, link, id, title, order or
-- Pray the Word progress is changed or removed.
--   • ${newTopics.length} new topics, inserted as status 'draft' (invisible until an editor publishes them).
--   • ${refRows.length} unique references (shared by topics, never duplicated; existing rows reused).
--   • ${linkRows.length} topic–passage links, all editorial_status 'needs_review' (invisible to participants).
--     For EXISTING topics they are appended as role 'supporting' AFTER the topic's last passage, so every
--     participant's Pray the Word position (a place in the visible list) stays exactly where it is.
-- ORDER OF RELEASE: deploy the API that filters editorial_status FIRST (routes/prayerTopics.ts, 2026-11-14),
-- then apply this. (The API reads the column with "*", so it is safe before and after the column exists.)
-- Every reference was checked against the Berean Standard Bible (bible.helloao.org): ${report.valid}/${report.references} valid on ${report.checkedAt}.
begin;

-- 1. Editorial columns (defaults keep every existing link published and visible).
alter table public.p2p_prayer_topics add column if not exists category text;
alter table public.p2p_topic_scriptures add column if not exists editorial_status text not null default 'published';
alter table public.p2p_topic_scriptures drop constraint if exists p2p_topic_scriptures_editorial_status_check;
alter table public.p2p_topic_scriptures add constraint p2p_topic_scriptures_editorial_status_check check (editorial_status in ('draft', 'needs_review', 'approved', 'published'));
alter table public.p2p_topic_scriptures add column if not exists editorial_title text;
alter table public.p2p_topic_scriptures add column if not exists passage_kind text;
create index if not exists idx_p2p_topic_scriptures_status on public.p2p_topic_scriptures(topic_id, editorial_status);

-- 2. Categories for existing topics, matched by title (never renamed).
update public.p2p_prayer_topics t set category = c.category
  from (values ${Object.entries(index.existingTopicCategories).map(([title, cat]) => `(${q(title)}, ${q(cat)})`).join(", ")}) as c(title, category)
 where t.title = c.title and t.category is null;

-- 3. New topics (draft), after the existing ones; a slug or title that already exists is skipped.
insert into public.p2p_prayer_topics (slug, title, description, display_order, status, category)
select s.slug, s.title, s.description, (select coalesce(max(display_order), 0) from public.p2p_prayer_topics) + s.n, 'draft', s.category
  from (values
${newTopics.map((t, i) => `    (${q(t.slug)}, ${q(t.title)}, ${q(t.description)}, ${i + 1}, ${q(t.category)})`).join(",\n")}
  ) as s(slug, title, description, n, category)
 where not exists (select 1 from public.p2p_prayer_topics x where x.slug = s.slug or lower(x.title) = lower(s.title));

-- 4. References: reuse an existing row for the same passage ("Psalm"/"Psalms" and "Song of Songs" treated alike).
create temporary table tmp_refs (book text, chapter int, sv int, ev int, display text) on commit drop;
insert into tmp_refs values
${refRows.map((r) => "  " + r).join(",\n")};
create or replace function pg_temp.same_book(a text, b text) returns boolean language sql immutable as $$
  select lower(a) = lower(b) or (lower(a) in ('psalm', 'psalms') and lower(b) in ('psalm', 'psalms'))
      or (lower(a) in ('song of solomon', 'song of songs') and lower(b) in ('song of solomon', 'song of songs')) $$;
insert into public.p2p_scripture_references (book, chapter, start_verse, end_verse, reference_display)
select r.book, r.chapter, r.sv, r.ev, r.display from tmp_refs r
 where not exists (select 1 from public.p2p_scripture_references x where pg_temp.same_book(x.book, r.book) and x.chapter = r.chapter and x.start_verse = r.sv and x.end_verse = r.ev);

-- 5. Links: needs_review, appended after each topic's existing passages (existing pairs are skipped).
create temporary table tmp_links (topic_title text, book text, chapter int, sv int, ev int, n int, etitle text, kind text, note text) on commit drop;
insert into tmp_links values
${linkRows.map((r) => "  " + r).join(",\n")};
insert into public.p2p_topic_scriptures (topic_id, scripture_id, role, display_order, editorial_note, editorial_status, editorial_title, passage_kind)
select t.id, r.id, 'supporting',
       (select coalesce(max(x.display_order), 0) from public.p2p_topic_scriptures x where x.topic_id = t.id) + l.n,
       l.note, 'needs_review', l.etitle, l.kind
  from tmp_links l
  join public.p2p_prayer_topics t on t.title = l.topic_title
  join lateral (select id from public.p2p_scripture_references x where pg_temp.same_book(x.book, l.book) and x.chapter = l.chapter and x.start_verse = l.sv and x.end_verse = l.ev order by x.created_at limit 1) r on true
on conflict (topic_id, scripture_id) do nothing;

commit;
-- Rollback (only what this added): delete from p2p_topic_scriptures where editorial_status = 'needs_review';
--   delete from p2p_prayer_topics where status = 'draft' and slug in (${newTopics.map((t) => q(t.slug)).join(", ")});
--   (references are shared and harmless; columns can stay or be dropped.)
`;
mkdirSync(path.join(repo, "docs", "proposals"), { recursive: true });
writeFileSync(path.join(repo, "docs", "proposals", "248_scripture_topics_expansion_PROPOSED.sql"), sql);

// 3. Review report.
const cat = Object.fromEntries(index.categories.map((c) => [c.key, c.title]));
const kinds = {}; for (const e of byKey.values()) kinds[e.p.kind] = (kinds[e.p.kind] ?? 0) + 1;
const ot = [...byKey.values()].filter((e) => ["GEN","EXO","LEV","NUM","DEU","JOS","JDG","RUT","1SA","2SA","1KI","2KI","1CH","2CH","EZR","NEH","EST","JOB","PSA","PRO","ECC","SNG","ISA","JER","LAM","EZK","DAN","HOS","JOL","AMO","OBA","JON","MIC","NAM","HAB","ZEP","HAG","ZEC","MAL"].includes(e.p.code)).length;
const md = [`# Explore Scripture by Topic — editorial review (${report.checkedAt})`, "",
  "Status: **needs editorial review**. Nothing here is visible to participants until a P2P editor approves it and the owner approves the database change (`docs/proposals/248_scripture_topics_expansion_PROPOSED.sql`).", "",
  "## Summary", "",
  `- Existing topics preserved: **${existingTitles.length}** (titles, ids, order and passages untouched; ${additions.length} receive additional passages for review).`,
  `- New topics proposed: **${newTopics.length}** (status draft).`,
  `- Topic–passage links proposed: **${linkRows.length}** (${newTopics.reduce((n, t) => n + t.parsed.length, 0)} on new topics, ${additions.reduce((n, t) => n + t.parsed.length, 0)} added to existing topics).`,
  `- Unique passages: **${byKey.size}** (${ot} Old Testament, ${byKey.size - ot} New Testament); shared by more than one topic: **${shared.length}**.`,
  `- Validated against the Berean Standard Bible text (bible.helloao.org): **${report.valid} of ${report.references}** references valid — book, chapter and both verse numbers exist. ${report.failed.length ? "Failures: " + report.failed.length : "No failures."}`,
  "- What validation does NOT check: whether each passage fits its topic. That is the editor's decision; every link is `needs_review`.",
  `- Passage kinds (unique passages): ${Object.entries(kinds).map(([k, n]) => `${k} ${n}`).join(" · ")}.`, "",
  "## Consolidated candidates (not added as new topics)", "",
  ...Object.entries(index.consolidated.intoExisting).map(([k, v]) => `- Covered by existing **${k}**: ${v.join(", ")}`),
  ...Object.entries(index.consolidated.mergedNew).filter(([k, v]) => v.length > 1 || v[0] !== k).map(([k, v]) => `- Merged into new **${k}**: ${v.join(", ")}`), "",
  "## Topics", "",
  ...index.categories.flatMap((c) => [`### ${c.title}`, "", "| Topic | New? | Passages proposed |", "|---|---|---|",
    ...newTopics.filter((t) => t.category === c.key).map((t) => `| ${t.title} | new (draft) | ${t.parsed.length} |`),
    ...additions.filter((t) => t.category === c.key).map((t) => `| ${t.title} | existing | +${t.parsed.length} (existing passages not counted — not readable without signing in) |`),
    ...existingTitles.filter((x) => index.existingTopicCategories[x] === c.key && !additions.some((a) => a.title === x)).map((x) => `| ${x} | existing | — (unchanged) |`), ""]),
  "## Passages needing particular editorial care", "",
  ...[...newTopics, ...additions].flatMap((t) => t.parsed.filter((p) => p.note).map((p) => `- **${t.title}** · ${p.display} — ${p.note}`)), "",
  "## Shared passages (one reference, several topics)", "",
  ...shared.map((e) => `- ${e.p.display}: ${e.topics.join(", ")}`), "",
  "## Every proposed passage", "",
  ...[...newTopics, ...additions].flatMap((t) => [`### ${t.title}${t.slug ? "" : " (existing — additions)"}`, "", ...t.parsed.map((p, i) => `${i + 1}. ${p.display} — ${p.title} *(${p.kind})*${p.note ? ` — note: ${p.note}` : ""}`), ""]),
];
writeFileSync(path.join(repo, "docs", "scripture-topics-review.md"), md.join("\n"));
console.log(`new topics ${newTopics.length}, existing with additions ${additions.length}, links ${linkRows.length}, unique passages ${byKey.size}, shared ${shared.length}`);
